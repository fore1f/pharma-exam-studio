def main() -> None:
    """過去10年過去問と照合し、法令データ・○×問題・比較表・暗記カードを統合保存する。"""
    all_qs = load_all_past_exam_questions()
    statutes: list[dict[str, Any]] = []
    for cfg in TARGET_LAWS:
        try:
            statutes.append(fetch_law_articles(cfg, all_qs))
        except Exception as exc:
            logger.exception("法令取得失敗 (%s): %s", cfg["name"], exc)

    pack = {
        "statutes": statutes,
        "ox_questions": build_ox_questions(),
        "comparison_tables": build_comparison_tables(),
        "flashcards": build_flashcards(),
    }

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out_path = OUT_DIR / "study_pack.json"
    out_path.write_text(json.dumps(pack, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    logger.info(
        "法令学習パック生成完了: 法令%d件(計%d条文), ○×%d問, 比較表%d件, 暗記カード%d枚 -> %s",
        len(statutes),
        sum(len(s["articles"]) for s in statutes),
        len(pack["ox_questions"]),
        len(pack["comparison_tables"]),
        len(pack["flashcards"]),
        out_path,
    )


if __name__ == "__main__":
    main()
