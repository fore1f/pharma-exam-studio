# 「解毒薬」に「毒薬」が部分一致する誤爆を防ぐ
FALSE_POSITIVE_CLEAN_RE = re.compile(r"解毒薬|抗毒|消毒薬")


def find_related_past_questions(
    law_short: str,
    law_aliases: list[str],
    art_num: str,
    art_title: str,
    all_qs: list[dict[str, Any]],
) -> list[str]:
    """過去10年分の過去問から、その条文に直接関連する法規・法令問題を高精度に抽出する。"""
    gates = STRICT_LAW_GATES.get(law_short, law_aliases)
    hints = ARTICLE_MATCH_HINTS.get((law_short, art_num), [])
    num_arabic = art_num.replace("_", "条の")
    explicit_patterns = [f"第{num_arabic}条", f"第 {num_arabic} 条", art_title]

    matched_ids: list[str] = []
    for q in all_qs:
        subj = q.get("subject", "")
        txt_raw = q.get("text", "")
        if not txt_raw:
            continue
        txt = FALSE_POSITIVE_CLEAN_RE.sub("", txt_raw)

        # 原則「法規・制度・倫理」科目、または他科目で法律名が明示されている問題のみ対象
        is_law_subj = "法規" in subj
        has_explicit_law_name = any(
            nm in txt for nm in (law_short, "薬剤師法", "医薬品医療機器等法", "医薬品、医療機器等", "麻薬及び向精神薬取締法", "毒物及び劇物取締法", "医療法")
        )
        if not is_law_subj and not ("実務" in subj and has_explicit_law_name):
            continue

        # ゲート1: その法令に確実に属する問題であること
        if not any(g in txt for g in gates):
            # 薬機法の毒薬・劇薬（解毒薬を除いた上で）
            if not (law_short == "薬機法" and art_num in ("44", "46", "48") and ("毒薬" in txt or "劇薬" in txt)):
                continue

        stem_part = FALSE_POSITIVE_CLEAN_RE.sub("", q.get("stem") or txt_raw.split("\n1 ")[0])

        # パターンA: 法令＋条文番号が明示されている（100%ドンピシャ）
        if any(ep in txt for ep in explicit_patterns):
            matched_ids.append(q["id"])
            continue

        if not hints:
            continue

        # 汎用すぎる1語を除外した固有ヒント
        generic_skip = {
            "医療法", "毒物", "劇物", "麻薬", "向精神薬", "免許", "登録", "保管", "廃棄",
            "表示", "副作用", "情報提供", "届出", "指導", "書面", "かぎ", "鍵",
            "病床", "病院", "診療所", "一般用医薬品", "薬局の管理者", "販売業",
        }
        specific_hints = [h for h in hints if h not in generic_skip]

        # パターンB: 問題文本体（stem）に固有ヒントが一致
        if any(h in stem_part for h in specific_hints):
            matched_ids.append(q["id"])
            continue

        # パターンC: 法規科目で全文に2語以上の固有ヒントが一致
        if is_law_subj and sum(1 for h in hints if h in txt) >= 2:
            matched_ids.append(q["id"])

    seen: set[str] = set()
    unique_ids: list[str] = []
    for qid in matched_ids:
        if qid not in seen:
            seen.add(qid)
            unique_ids.append(qid)
    return unique_ids


def fetch_law_articles(law_cfg: dict[str, Any], all_qs: list[dict[str, Any]]) -> dict[str, Any]:
    """e-Gov API v2から法令XMLの本則のみを取得し、赤シート語句と過去10年出題回数を付与する。"""
    law_id = law_cfg["id"]
    url = f"{EGOV_API_BASE}/{law_id}?response_format=xml"
    logger.info("e-Gov法令取得中: %s (%s)", law_cfg["name"], law_id)
    resp = httpx.get(url, follow_redirects=True, timeout=45)
    resp.raise_for_status()

    root = ET.fromstring(resp.content)
    law_num = ""
    ln_el = root.find(".//law_num")
    if ln_el is None:
        ln_el = root.find(".//LawNum")
    if ln_el is not None and ln_el.text:
        law_num = ln_el.text.strip()

    wanted = set(law_cfg["articles"])
    articles_out: list[dict[str, Any]] = []

    main_prov = root.find(".//MainProvision")
    search_root = main_prov if main_prov is not None else root

    for art in search_root.findall(".//Article"):
        num_attr = art.get("Num", "")
        if num_attr not in wanted:
            continue

        caption_el = art.find("ArticleCaption")
        title_el = art.find("ArticleTitle")
        caption = _extract_text(caption_el).strip() if caption_el is not None else ""
        title = _extract_text(title_el).strip() if title_el is not None else f"第{num_attr}条"

        paragraphs: list[str] = []
        for para in art.findall("Paragraph"):
            p_num_el = para.find("ParagraphNum")
            p_num = _extract_text(p_num_el).strip() if p_num_el is not None else ""
            sentences = [
                _extract_text(s).strip() for s in para.findall(".//ParagraphSentence/Sentence")
            ]
            p_text = (f"{p_num}　" if p_num else "") + "".join(sentences)
            if p_text.strip():
                paragraphs.append(p_text.strip())

            items = para.findall("Item")
            for item in items[:6]:
                it_title = _extract_text(item.find("ItemTitle")).strip() if item.find("ItemTitle") is not None else ""
                it_sents = [
                    _extract_text(s).strip() for s in item.findall(".//ItemSentence/Sentence")
                ]
                it_text = f"  {it_title} " + "".join(it_sents)
                if it_text.strip():
                    paragraphs.append(it_text.rstrip())

        full_body = "\n".join(paragraphs)

        # 赤シート用キーワード抽出（長い語句を優先して最大30語）
        keywords: list[str] = []
        for pat in CLOZE_PATTERNS:
            for m in pat.findall(full_body):
                if m and m not in keywords:
                    keywords.append(m)

        # 過去10年の出題実績を照合
        related_qids = find_related_past_questions(
            law_cfg["short"],
            law_cfg.get("law_aliases", [law_cfg["short"]]),
            num_attr,
            title,
            all_qs,
        )

        articles_out.append(
            {
                "num": num_attr,
                "title": title,
                "caption": caption,
                "body": full_body,
                "point": ARTICLE_STUDY_POINTS.get((law_cfg["short"], num_attr), ""),
                "keywords": keywords[:32],
                "exam_count": len(related_qids),
                "related_qids": related_qids[:25],
            }
        )

    total_hits = sum(a["exam_count"] for a in articles_out)
    logger.info(
        "  抽出完了: %s -> %d 条文（過去10年関連延べ %d 問マッチ）",
        law_cfg["name"],
        len(articles_out),
        total_hits,
    )
    return {
        "id": law_id,
        "name": law_cfg["name"],
        "short": law_cfg["short"],
        "law_num": law_num,
        "articles": articles_out,
    }


